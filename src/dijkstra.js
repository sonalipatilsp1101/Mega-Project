export function findShortestPath(graph, startNode, endNode, blockedNextNode = null) {
  const distances = {};
  const prev = {};
  const pq = new Set(Object.keys(graph));

  Object.keys(graph).forEach(node => {
    distances[node] = Infinity;
  });
  distances[startNode] = 0;

  while (pq.size > 0) {
    let currNode = null;
    let shortestDist = Infinity;

    pq.forEach(node => {
      if (distances[node] < shortestDist) {
        shortestDist = distances[node];
        currNode = node;
      }
    });

    if (currNode === null || shortestDist === Infinity) break;
    if (currNode === endNode) break;

    pq.delete(currNode);

    const neighbors = graph[currNode] || {};
    for (const neighbor in neighbors) {
      if (!pq.has(neighbor)) continue;
      
      let weight = neighbors[neighbor];
      if (currNode === startNode && neighbor === blockedNextNode) {
        weight *= 100; // Block primary path to trigger alternative route
      }

      const alt = distances[currNode] + weight;
      if (alt < distances[neighbor]) {
        distances[neighbor] = alt;
        prev[neighbor] = currNode;
      }
    }
  }

  const path = [];
  let u = endNode;
  while (u !== undefined) {
    path.unshift(u);
    u = prev[u];
  }

  if (path.length === 1 && path[0] !== startNode) {
    return { distance: null, path: [] };
  }

  return {
    distance: distances[endNode] === Infinity ? null : Number(distances[endNode].toFixed(1)),
    path: path
  };
}

export function findNearestHospitalDynamic(graph, startNode, isBlocked = false) {
  // First, find normal shortest path to get the primary next step from startNode
  let initialHospital = null;
  let minDistance = Infinity;
  let bestPath = [];

  const actualHospitalList = [
    "CPR_Hospital", "Sachin_Multispecialty", "Aster_Aadhar", "Surya_Hospital", 
    "Shrawastie_Hospital", "Sunshine_Multispecialty", "Diamond_Hospital", 
    "Tulip_Traumacare", "Athaayu_Hospital", "Apple_Saraswati", "Krishna_Hospital", 
    "Asian_Hospital", "OmHospital"
  ];

  actualHospitalList.forEach(hospital => {
    const result = findShortestPath(graph, startNode, hospital, null);
    if (result.distance !== null && result.distance < minDistance) {
      minDistance = result.distance;
      initialHospital = hospital;
      bestPath = result.path;
    }
  });

  // If traffic is blocked, block the immediate next node (bestPath[1]) and re-run Dijkstra to find alternative route!
  let blockedNode = null;
  if (isBlocked && bestPath.length > 1) {
    blockedNode = bestPath[1];
  }

  if (isBlocked) {
    let altHospital = null;
    let altMinDistance = Infinity;
    let altBestPath = [];

    actualHospitalList.forEach(hospital => {
      const result = findShortestPath(graph, startNode, hospital, blockedNode);
      if (result.distance !== null && result.distance < altMinDistance) {
        altMinDistance = result.distance;
        altHospital = hospital;
        altBestPath = result.path;
      }
    });

    if (altBestPath.length > 1) {
      return {
        hospital: altHospital || initialHospital,
        distance: altMinDistance,
        path: altBestPath
      };
    }
  }

  return {
    hospital: initialHospital || "CPR_Hospital",
    distance: minDistance === Infinity ? 0 : minDistance,
    path: bestPath
  };
}